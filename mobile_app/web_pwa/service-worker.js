// CyberShield AI Mobile Guardian Service Worker
const CACHE_NAME = 'cybershield-mobile-v1';
const ASSETS = [
  '/mobile',
  '/mobile_static/css/mobile.css',
  '/mobile_static/js/mobile_agent.js',
  '/mobile_static/icon.ico',
  '/mobile_static/manifest.json'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME).then(cache => {
      return cache.addAll(ASSETS).catch(() => {});
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys().then(keys => {
      return Promise.all(
        keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key))
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', event => {
  // Network first for real-time WebSocket and API endpoints
  if (event.request.url.includes('/api/') || event.request.url.includes('/ws')) {
    return;
  }
  event.respondWith(
    fetch(event.request).catch(() => caches.match(event.request))
  );
});
